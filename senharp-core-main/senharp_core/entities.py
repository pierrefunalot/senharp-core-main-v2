    new_consumer_loans: float = 0.0
    consumer_loan_repayments: float = 0.0
    consumer_loans: float = 0.0

    # Current-period interest received from households
    consumer_loan_interest_income: float = 0.0

    # =========================================================
    # HOUSEHOLD DEPOSITS
    # =========================================================

    # Opening household-deposit liabilities.
    previous_household_deposits: float = 0.0

    # Closing household-deposit liabilities.
    household_deposits: float = 0.0

