from dataclasses import dataclass
from enum import Enum, IntEnum

class Scenario(str, Enum):
    BASELINE = "baseline"
    CARBON_TAX = "carbon_tax"
    GREEN_DEAL = "green_deal"
    POST_GROWTH = "post_growth"

class PolicyMode(str, Enum):
    """Political activation regime for a policy package."""

    OFF = "off"
    FIXED = "fixed"
    ENDOGENOUS = "endogenous"
    
class EmploymentStatus(IntEnum):
    """Employment states used in SEN-HARP."""

    UNEMPLOYED = 0
    LOW_SKILLED_BROWN = 1
    LOW_SKILLED_GREEN = 2
    JOB_GUARANTEE = 3
    HIGH_SKILLED_BROWN = 4
    HIGH_SKILLED_GREEN = 5
    RESKILLING = 6


class SkillLevel(IntEnum):
    """Skill levels used in labour-market matching."""

    LOW_SKILL = 0
    HIGH_SKILL = 1

class Sector(str, Enum):
    """Economic sectors represented in SEN-HARP."""

    AGRICULTURE = "agriculture"
    ENERGY = "energy"
    HOUSING = "housing"
    TRANSPORT = "transport"
    INDUSTRY = "industry"
    TECHNOLOGY = "technology"
    
