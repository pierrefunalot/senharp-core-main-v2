    risk_appetite: float = 0.82
    market_share: float = 0.0

    green_loans: float = 0.0
    brown_loans: float = 0.0

    # =========================================================
    # BANK LOANS TO FIRMS
    # =========================================================

    # Opening stocks of bank loans to firms.
    previous_brown_loans: float = 0.0
    previous_green_loans: float = 0.0

    # New loans effectively used for delivered investment.
    new_brown_loans: float = 0.0
    new_green_loans: float = 0.0

    # Repayment of firm-loan principal.
    brown_loan_repayments: float = 0.0
    green_loan_repayments: float = 0.0

    # Interest received from firms.
    # This remains zero until firm interest payments are activated.
    firm_loan_interest_income: float = 0.0

    reserves: float = 0.0
    government_bonds: float = 0.0
    equity: float = 0.0

    interest_on_reserves: float = 0.0

    # =========================================================
    # GOVERNMENT-BOND HOLDINGS
    # =========================================================

    # Government bonds held at the beginning of the period.
    previous_government_bonds: float = 0.0

    # Signed change in government-bond holdings during the
    # current period. A negative value represents redemption
    # or sale of bonds.
